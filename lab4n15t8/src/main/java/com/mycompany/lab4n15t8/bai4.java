    private void btnTimActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTimActionPerformed
        // TODO add your handling code here:
           try {

            int n = Integer.parseInt(
                    txtN.getText().trim()
            );

            // Kiểm tra N
            if (n < 0) {

                lblKetQua.setText(
                        "N phải >= 0"
                );

                return;
            }

            // Giới hạn N
            if (n > 10000) {

                lblKetQua.setText(
                        "N quá lớn, hãy nhập N <= 10000"
                );

                return;
            }

            // Thông báo đang tính
            lblKetQua.setText(
                    "Đang tính..."
            );

            progressBar.setValue(0);

            // Không cho bấm nhiều lần
            btnTim.setEnabled(false);

            // Tạo SwingWorker
            FibonacciWorker worker
                    = new FibonacciWorker(n);

            // Theo dõi tiến trình
            worker.addPropertyChangeListener(evt2 -> {

                if ("progress".equals(
                        evt2.getPropertyName())) {

                    int progress
                            = (Integer) evt2.getNewValue();

                    progressBar.setValue(progress);
                }
            });

            // Chạy background
            worker.execute();

        } catch (NumberFormatException e) {

            lblKetQua.setText(
                    "Vui lòng nhập số nguyên!"
            );
        }
    }//GEN-LAST:event_btnTimActionPerformed

