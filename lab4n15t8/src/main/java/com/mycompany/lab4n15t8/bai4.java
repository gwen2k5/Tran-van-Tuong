 // Hàm Fibonacci sử dụng memoization
    private BigInteger fibonacci(int n) {
        if (memo.containsKey(n)) {
            return memo.get(n);
        }

        BigInteger result = fibonacci(n - 1).add(fibonacci(n - 2));

        // Lưu kết quả vào Map
        memo.put(n, result);

        return result;
        
    }
 private class FibonacciWorker
            extends SwingWorker<BigInteger, Integer> {

        private final int n;

        public FibonacciWorker(int n) {
            this.n = n;
        }

        @Override
        protected BigInteger doInBackground() throws Exception {

            // Tính Fibonacci
            BigInteger result = fibonacci(n);

            // Giả lập tiến trình
            for (int i = 0; i <= 100; i++) {

                Thread.sleep(5);

                setProgress(i);
            }

            return result;
        }

        @Override
        protected void done() {

            try {

                // Lấy kết quả từ SwingWorker
                BigInteger result = get();

                lblKetQua.setText(
                        "F(" + n + ") = " + result
                );

                progressBar.setValue(100);

                // Cho phép bấm lại
                btnTim.setEnabled(true);

            } catch (Exception e) {

                lblKetQua.setText(
                        "Có lỗi khi tính toán!"
                );

                btnTim.setEnabled(true);
            }
        }
    }
    
